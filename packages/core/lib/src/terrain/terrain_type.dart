/// マスの地形タイプ（地形タイプ軸）。
///
/// 出典: `docs/terrain.md` §2「地形タイプ一覧（5種）」。
/// この5種と過不足なく一致させること（Issue #33 受け入れ基準・Issue #70で7種から5種に改訂）。
/// 建築状態軸（未建築/建築後）とは独立した軸であり、本 enum は建築状態を表さない
/// （terrain.md §1）。
///
/// 【2026-09-08 Issue #70】地形タイプから農地・市街を除外した（代表決定）。
/// 「地図が与えるのは自然、文明はプレイヤーが建てる」という設計思想に基づき、文明
/// （畑・農場・工場・住宅等）はプレイヤーが空き地に建設する対象として `docs/buildings.md`
/// に一本化し、地形タイプとしては固定配置しない。これにより旧・地形産出（農地→野菜/
/// フルーツ）と建物産出（畑→野菜/フルーツ）の二重定義が解消された（terrain.md §2）。
enum TerrainType {
  /// 空き地。産出資材なし（産出0）。唯一、建物を建てられる地形（terrain.md §2）。
  vacantLot,

  /// 森。産出資材: 木（terrain.md §2）。
  forest,

  /// 山。産出資材: 石・鉄（terrain.md §2）。
  mountain,

  /// 水辺（川・湖）。産出資材: 水（terrain.md §2）。
  waterside,

  /// 海。産出資材: 塩。建築不可だが開放対象（terrain.md §2・§7）。
  sea,
}
